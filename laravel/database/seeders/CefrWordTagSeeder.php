    /**
     * Word lookup and pivot insert chunk size.
     */
    private const CHUNK_SIZE = 500;

    public function run(): void
    {
        $languageId = Language::query()->where('code', 'en')->value('id');

        if ($languageId === null) {
            $this->command?->warn('CefrWordTagSeeder: English language (code en) not found — skipping.');

            return;
        }

        $this->sync(self::LISTS, $languageId);
    }

    /**
     * The testable sync core: full-replace every CEFR tag's attachments from
     * $lists (raw entries, normalized here). Idempotent — a re-run attaches
     * nothing new; the unique (word_id, tag_id) pivot pair plus
     * insertOrIgnore guard that regardless.
     *
     * @param  array<string, list<string>>  $lists  slug => raw word entries
     */
    public function sync(array $lists, int $languageId): void
    {
        $now = now();

        foreach (self::LEVELS as $slug => $name) {
            $entries = $this->normalize($lists[$slug] ?? []);

            $tag = Tag::query()->updateOrCreate(['slug' => $slug], ['name' => $name]);

            // Full replace: detach everything, then re-attach from the list —
            // this is what removes words dropped from the list.
            DB::table('tagged_words')->where('tag_id', $tag->id)->delete();

            $attached = 0;
            $matched = [];

            foreach (array_chunk($entries, self::CHUNK_SIZE) as $chunk) {
                // get(), not pluck('id', 'l_word'): one spelling maps to
                // several rows (one per part of speech) and every one of
                // them must attach.
                $words = Word::query()
                    ->where('language_id', $languageId)
                    ->whereIn('l_word', $chunk)
                    ->get(['id', 'l_word']);

                if ($words->isEmpty()) {
                    continue;
                }

                $rows = [];
                foreach ($words as $word) {
                    $matched[$word->l_word] = true;
                    $rows[] = [
                        'word_id' => $word->id,
                        'tag_id' => $tag->id,
                        'created_at' => $now,
                        'updated_at' => $now,
                    ];
                }

                foreach (array_chunk($rows, self::CHUNK_SIZE) as $rowChunk) {
                    DB::table('tagged_words')->insertOrIgnore($rowChunk);
                }

                $attached += count($rows);
            }

            $unmatched = array_values(array_diff($entries, array_keys($matched)));

            $this->command?->line(sprintf(
                'CEFR %s: attached %d %s.%s',
                $slug,
                $attached,
                $attached === 1 ? 'word' : 'words',
                $unmatched === [] ? '' : ' — unmatched (skipped): '.implode(', ', $unmatched),
            ));
        }
    }

    /**
     * The spec's normalization, applied defensively on every run: trim,
     * lowercase, U+2019 → straight apostrophe, drop entries with no letters,
     * dedupe (first-occurrence order preserved).
     *
     * @param  list<string>  $lines
     * @return list<string>
     */
    private function normalize(array $lines): array
    {
        $entries = [];

        foreach ($lines as $line) {
            $entry = str_replace('’', "'", mb_strtolower(trim((string) $line)));

            if (preg_match('/\p{L}/u', $entry) === 1) {
                $entries[] = $entry;
            }
        }

        return array_values(array_unique($entries));
    }
